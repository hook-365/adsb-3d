// Airports layer: every runway where it lies, the approach path to the
// lit hard-surface ones, and a name label on each airport.
//
// Until this existed an airport was a smudge on the basemap, and the
// airspace shelves and the close-up camera had nothing to anchor to. With
// it, arrivals visibly line up on a final and a Class B has a centre.
//
// runways-data.json is generated by scripts/build-runways.py from
// OurAirports (public domain; do not hand-edit) for the airports in
// feed/explore-airports.json, and fetched once as a hashed asset when the
// layer is first turned on. Only runways with both ends surveyed are in it,
// so small strips may be missing.
//
// Runways are flat quads resting on the drawn terrain, merged into one
// mesh; approach paths are one LineSegments. An approach is a straight
// 3 degree descent to the threshold along the runway's own centreline: the
// generic shape of an instrument approach, not that runway's published
// procedure, and drawn for both ends whichever is in use.
//
// Everything above the mount function is pure so it can be unit tested.

const FT_PER_NM = 6076.12;
const NM_PER_DEG = 60;
/** Runways are drawn at least this wide (NM) so they read from a few miles up. */
const MIN_DRAWN_WIDTH_NM = 0.035;
/** How far out the approach path starts, and its descent angle. */
const APPROACH_NM = 10;
const GLIDE_TAN = Math.tan((3 * Math.PI) / 180);
/** Pieces per approach: the altitude curve bends a straight descent. */
const APPROACH_STEPS = 8;
/** Height over the drawn ground, scene units: clear of the basemap, under the icons. */
const RUNWAY_LIFT = 0.04;
const LABEL_RADIUS_NM = 150;
const MAX_LABELS = 24;
const ELEVATION_SETTLE_MS = 1500;
const RUNWAY_COLOR = 0xd7e0ea;
const APPROACH_COLOR = 0x8fd3ff;

export interface Runway {
  /** Idents of the two ends, low number first ("12L", "30R"). */
  lowIdent: string;
  highIdent: string;
  lowLat: number;
  lowLon: number;
  highLat: number;
  highLon: number;
  widthFt: number;
  lighted: boolean;
  hard: boolean;
  lowElevFt: number;
  highElevFt: number;
}

type RawRunway = [string, string, number, number, number, number, number, number, number, number, number];

/** Parse the generated file: ICAO code → runways. Rows that do not fit are dropped. */
export function decodeRunways(raw: unknown): Map<string, Runway[]> {
  const out = new Map<string, Runway[]>();
  const table = (raw as { runways?: Record<string, RawRunway[]> } | null)?.runways;
  if (!table || typeof table !== 'object') return out;
  for (const [icao, rows] of Object.entries(table)) {
    if (!Array.isArray(rows)) continue;
    const list: Runway[] = [];
    for (const r of rows) {
      if (!Array.isArray(r) || r.length < 11 || ![r[2], r[3], r[4], r[5]].every((v) => Number.isFinite(v))) continue;
      list.push({
        lowIdent: String(r[0]),
        highIdent: String(r[1]),
        lowLat: r[2],
        lowLon: r[3],
        highLat: r[4],
        highLon: r[5],
        widthFt: Number(r[6]) || 0,
        lighted: r[7] === 1,
        hard: r[8] === 1,
        lowElevFt: Number(r[9]) || 0,
        highElevFt: Number(r[10]) || 0,
      });
    }
    if (list.length > 0) out.set(icao, list);
  }
  return out;
}

/** Runway length in feet (flat-earth over a couple of miles is exact enough). */
export function runwayLengthFt(r: Runway): number {
  const cos = Math.cos((((r.lowLat + r.highLat) / 2) * Math.PI) / 180);
  const north = (r.highLat - r.lowLat) * NM_PER_DEG;
  const east = (r.highLon - r.lowLon) * NM_PER_DEG * cos;
  return Math.hypot(north, east) * FT_PER_NM;
}

/**
 * The four corners of a runway as [lat, lon] pairs, in order around the
 * rectangle, `widthNm` wide.
 */
export function runwayCorners(r: Runway, widthNm: number): [number, number][] {
  const cos = Math.cos((((r.lowLat + r.highLat) / 2) * Math.PI) / 180);
  const north = (r.highLat - r.lowLat) * NM_PER_DEG;
  const east = (r.highLon - r.lowLon) * NM_PER_DEG * cos;
  const len = Math.hypot(north, east) || 1;
  // Half the width, across the runway, back in degrees.
  const dLat = ((-east / len) * widthNm) / 2 / NM_PER_DEG;
  const dLon = ((north / len) * widthNm) / 2 / (NM_PER_DEG * cos);
  return [
    [r.lowLat + dLat, r.lowLon + dLon],
    [r.highLat + dLat, r.highLon + dLon],
    [r.highLat - dLat, r.highLon - dLon],
    [r.lowLat - dLat, r.lowLon - dLon],
  ];
}

/**
 * Points down a 3 degree approach to one end of a runway, far end first:
 * [lat, lon, altitude ft MSL] from `distNm` out to the threshold.
 */
export function approachPath(
  thresholdLat: number,
  thresholdLon: number,
  thresholdElevFt: number,
  farEndLat: number,
  farEndLon: number,
  distNm = APPROACH_NM,
  steps = APPROACH_STEPS,
): [number, number, number][] {
  const cos = Math.cos((thresholdLat * Math.PI) / 180);
  // Unit vector from the far end of the runway through the threshold and on.
  const north = (thresholdLat - farEndLat) * NM_PER_DEG;
  const east = (thresholdLon - farEndLon) * NM_PER_DEG * cos;
  const len = Math.hypot(north, east) || 1;
  const out: [number, number, number][] = [];
  for (let i = steps; i >= 0; i--) {
    const d = (distNm * i) / steps;
    out.push([
      thresholdLat + ((north / len) * d) / NM_PER_DEG,
      thresholdLon + ((east / len) * d) / (NM_PER_DEG * cos),
      thresholdElevFt + d * GLIDE_TAN * FT_PER_NM,
    ]);
  }
  return out;
}

/** An airport with runways, as the layer and its label know it. */
export interface AirportSite {
  airport: Airport;
  runways: Runway[];
  distanceNm: number;
}

/**
 * Airports within `rangeNm` that have runway data. `airports` is in
 * significance order (large first), which is the order kept.
 */
export function sitesNear(
  airports: readonly Airport[],
  runways: ReadonlyMap<string, Runway[]>,
  rangeNm: number,
  distanceNm: (lat: number, lon: number) => number,
): AirportSite[] {
  const out: AirportSite[] = [];
  for (const airport of airports) {
    const list = runways.get(airport.icao);
    if (!list) continue;
    const d = distanceNm(airport.place.lat, airport.place.lon);
    if (d <= rangeNm) out.push({ airport, runways: list, distanceNm: d });
  }
  return out;
}

// ── Loader ──────────────────────────────────────────────────────────

let runwayTable: Map<string, Runway[]> | null = null;
let loading: Promise<void> | null = null;
const listeners = new Set<() => void>();

function load(): void {
  if (runwayTable || loading) return;
  setLoading('airports', t('settings.group_airports'));
  loading = Promise.all([fetch(dataUrl).then((res) => (res.ok ? (res.json() as Promise<unknown>) : null)), loadAirports()])
    .then(([raw]) => {
      if (!raw) throw new Error('runway data unavailable');
      runwayTable = decodeRunways(raw);
      for (const fn of listeners) fn();
    })
    .catch((err: unknown) => {
      console.warn('[airports] could not load runways', err);
      loading = null;
    })
    .finally(() => setLoading('airports', null));
}

/** Runways of one airport, when the layer's data has loaded. */
export function runwaysOf(icao: string): readonly Runway[] {
  return runwayTable?.get(icao) ?? [];
}

export function airportsActive(): boolean {
  const s = getSettings();
  return s.airportRunways || s.airportApproaches;
}

export interface AirportsOptions {
  /** An airport's label was clicked. `center` is where it is in the scene. */
  onSelect?: (site: AirportSite, center: Vector3) => void;
}

export function mountAirports(parent: Group, options: AirportsOptions = {}): void {
  const group = new Group();
  group.name = 'airports';
  const labelGroup = new Group();
  group.add(labelGroup);

  const runwayMat = new MeshBasicMaterial({
    color: RUNWAY_COLOR,
    transparent: true,
    opacity: 0.8,
    side: DoubleSide,
    depthWrite: false,
    clippingPlanes: DIORAMA_PLANES,
    // Flat on the terrain mesh: pull toward the camera so a corner that
    // dips under a triangle still draws (the ground icons do the same).
    polygonOffset: true,
    polygonOffsetFactor: -2,
    polygonOffsetUnits: -6,
  });
  const approachMat = new LineBasicMaterial({
    color: APPROACH_COLOR,
    transparent: true,
    opacity: 0.4,
    depthWrite: false,
    clippingPlanes: DIORAMA_PLANES,
  });

  let runwayMesh: Mesh | null = null;
  let approachLines: LineSegments | null = null;
  let attached = false;
  let settleTimer: ReturnType<typeof setTimeout> | undefined;
  const tmp = new Vector3();

  const dispose = (): void => {
    for (const obj of [runwayMesh, approachLines]) {
      if (!obj) continue;
      obj.removeFromParent();
      obj.geometry.dispose();
    }
    runwayMesh = null;
    approachLines = null;
    for (const child of Array.from(labelGroup.children)) {
      labelGroup.remove(child);
      if (child instanceof CSS2DObject) child.element.remove();
    }
  };

  const rebuild = (): void => {
    dispose();
    const airports = getAirports();
    if (!attached || !runwayTable || !airports) return;
    const s = getSettings();
    const sites = sitesNear(airports, runwayTable, RANGE_NM, distanceFromHomeNm);

    if (s.airportRunways) {
      const positions: number[] = [];
      const indices: number[] = [];
      for (const { runways } of sites) {
        for (const r of runways) {
          const base = positions.length / 3;
          const widthNm = Math.max(r.widthFt / FT_PER_NM, MIN_DRAWN_WIDTH_NM);
          for (const [lat, lon] of runwayCorners(r, widthNm)) {
            terrainSurface(lat, lon, tmp);
            positions.push(tmp.x, tmp.y + RUNWAY_LIFT, tmp.z);
          }
          indices.push(base, base + 1, base + 2, base, base + 2, base + 3);
        }
      }
      if (indices.length > 0) {
        const geom = new BufferGeometry();
        geom.setAttribute('position', new BufferAttribute(new Float32Array(positions), 3));
        geom.setIndex(indices);
        runwayMesh = new Mesh(geom, runwayMat);
        runwayMesh.renderOrder = 3;
        runwayMesh.frustumCulled = false;
        runwayMesh.userData = { kind: 'runways' };
        group.add(runwayMesh);
      }
    }

    if (s.airportApproaches) {
      const lines: number[] = [];
      const add = (path: [number, number, number][]): void => {
        for (let i = 0; i + 1 < path.length; i++) {
          for (const [lat, lon, altFt] of [path[i]!, path[i + 1]!]) {
            toScene(lat, lon, altFt, tmp);
            lines.push(tmp.x, tmp.y, tmp.z);
          }
        }
      };
      for (const { runways } of sites) {
        for (const r of runways) {
          if (!r.lighted || !r.hard) continue;
          add(approachPath(r.lowLat, r.lowLon, r.lowElevFt, r.highLat, r.highLon));
          add(approachPath(r.highLat, r.highLon, r.highElevFt, r.lowLat, r.lowLon));
        }
      }
      if (lines.length > 0) {
        const geom = new BufferGeometry();
        geom.setAttribute('position', new BufferAttribute(new Float32Array(lines), 3));
        approachLines = new LineSegments(geom, approachMat);
        approachLines.renderOrder = 7;
        approachLines.frustumCulled = false;
        approachLines.userData = { kind: 'approaches' };
        group.add(approachLines);
      }
    }

    if (s.airportLabels) {
      // `sites` is already large airports first; among those, nearest.
      const labelled = sites.filter((x) => x.distanceNm <= LABEL_RADIUS_NM).slice(0, MAX_LABELS);
      for (const site of labelled) {
        const { airport } = site;
        const el = document.createElement('div');
        el.className = 'aircraft-label airport-label';
        el.dataset.icao = airport.icao;
        el.textContent = airport.icao;
        terrainSurface(airport.place.lat, airport.place.lon, tmp);
        const center = tmp.clone();
        if (options.onSelect) {
          const pick = (): void => options.onSelect?.(site, center);
          el.classList.add('clickable');
          el.setAttribute('role', 'button');
          el.tabIndex = 0;
          el.title = airport.name;
          el.addEventListener('click', (e) => {
            e.stopPropagation();
            pick();
          });
          el.addEventListener('keydown', (e) => {
            if (e.key !== 'Enter' && e.key !== ' ') return;
            e.preventDefault();
            pick();
          });
        }
        const label = new CSS2DObject(el);
        label.position.copy(center).setY(center.y + 0.25);
        labelGroup.add(label);
      }
    }
  };

  const sync = (): void => {
    const on = airportsActive();
    if (on && !attached) {
      parent.add(group);
      attached = true;
    } else if (!on && attached) {
      parent.remove(group);
      attached = false;
    }
    if (on) load();
    rebuild();
  };

  const layerKey = (): string => {
    const s = getSettings();
    return `${s.airportRunways}|${s.airportApproaches}|${s.airportLabels}|${s.altitudeExaggeration}|${s.altitudeCurveBias}`;
  };
  let lastKey = layerKey();
  subscribeSettings(() => {
    const key = layerKey();
    if (key === lastKey) return;
    lastKey = key;
    sync();
  });
  listeners.add(rebuild);
  subscribeHome(rebuild);
  // Runways rest on the terrain, which streams in after boot and after a
  // feed switch: place them again once it has settled.
  subscribeElevation(() => {
    if (!attached || !terrainActive()) return;
    clearTimeout(settleTimer);
    settleTimer = setTimeout(rebuild, ELEVATION_SETTLE_MS);
  });
  sync();
}
