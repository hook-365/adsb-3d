import { CSS2DObject } from 'three/examples/jsm/renderers/CSS2DRenderer.js';
import dataUrl from './artcc-data.json?url';
import { RANGE_NM, subscribeHome } from '../core/config';
import { distanceFromHomeNm } from '../core/coords';
import { t } from '../core/i18n';
import { setLoading } from '../core/loading';
import { getSettings, subscribeSettings } from '../core/settings';
import { DIORAMA_PLANES } from './diorama-clip';
import { yieldToAircraft } from './label-yield';
import { terrainSurface } from './tiles';

// US air route traffic control centres (ARTCCs): the twenty-odd regions
// en-route traffic is handed between. Drawn as outlines on the ground,
// named where a boundary crosses the scope, and read for the aircraft
// card's Centre row. That row says which centre's airspace an aircraft is
// in, which is geometry; it does not claim who the aircraft is talking to
// (below a centre's floor it is with an approach control or a tower).
//
// artcc-data.json is generated by scripts/build-artcc.py from FAA open
// data (public domain). Regenerate, do not hand-edit. Everything above the
// loader is pure.

export interface Centre {
  id: string;
  name: string;
  /** Outer rings as [lat, lon] pairs. */
  rings: [number, number][][];
  /** [south, west, north, east], for turning points away early. */
  bbox: [number, number, number, number];
}

const COLOR = 0x9fb4c8;
/** Longest drawn piece of a boundary, NM: the ground it lies on is not flat. */
const MAX_PIECE_NM = 6;
/** How far inside its own side of the boundary a centre's name sits, NM. */
const LABEL_INSET_NM = 7;

/** Parse the generated file. Entries that do not fit are dropped. */
export function decodeCentres(raw: unknown): Centre[] {
  const list = (raw as { centres?: unknown } | null)?.centres;
  if (!Array.isArray(list)) return [];
  const out: Centre[] = [];
  for (const item of list as { id?: unknown; name?: unknown; rings?: unknown }[]) {
    if (typeof item?.id !== 'string' || typeof item.name !== 'string' || !Array.isArray(item.rings)) continue;
    const rings = (item.rings as unknown[]).filter(
      (r): r is [number, number][] => Array.isArray(r) && r.length >= 4 && r.every((p) => Array.isArray(p) && p.length === 2),
    );
    if (rings.length === 0) continue;
    const bbox: [number, number, number, number] = [90, 180, -90, -180];
    for (const ring of rings) {
      for (const [lat, lon] of ring) {
        if (lat < bbox[0]) bbox[0] = lat;
        if (lon < bbox[1]) bbox[1] = lon;
        if (lat > bbox[2]) bbox[2] = lat;
        if (lon > bbox[3]) bbox[3] = lon;
      }
    }
    out.push({ id: item.id, name: item.name, rings, bbox });
  }
  return out;
}

function inRing(lat: number, lon: number, ring: readonly [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [aLat, aLon] = ring[i]!;
    const [bLat, bLon] = ring[j]!;
    if (aLat > lat !== bLat > lat && lon < ((bLon - aLon) * (lat - aLat)) / (bLat - aLat) + aLon) inside = !inside;
  }
  return inside;
}

/** The centre whose airspace a point is in, or null outside them all. */
export function centreAt(centres: readonly Centre[], lat: number, lon: number): Centre | null {
  for (const c of centres) {
    if (lat < c.bbox[0] || lat > c.bbox[2] || lon < c.bbox[1] || lon > c.bbox[3]) continue;
    if (c.rings.some((ring) => inRing(lat, lon, ring))) return c;
  }
  return null;
}

// ── Loader ──────────────────────────────────────────────────────────

let centres: Centre[] | null = null;
let loading: Promise<void> | null = null;
const listeners = new Set<() => void>();

export function getCentres(): readonly Centre[] | null {
  return centres;
}

export function subscribeCentres(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function centresActive(): boolean {
  return getSettings().airspaceCenters;
}

function load(): void {
  if (centres || loading) return;
  setLoading('artcc', t('settings.airspace_centers'));
  loading = fetch(dataUrl)
    .then((res) => {
      if (!res.ok) throw new Error(`centre boundaries: HTTP ${res.status}`);
      return res.json() as Promise<unknown>;
    })
    .then((raw) => {
      centres = decodeCentres(raw);
      for (const fn of listeners) fn();
    })
    .catch((err: unknown) => {
      console.warn('[artcc] could not load', err);
      loading = null;
    })
    .finally(() => setLoading('artcc', null));
}

export function mountCentres(parent: Group): void {
  const group = new Group();
  group.name = 'artcc';
  const labelGroup = new Group();
  group.add(labelGroup);
  yieldToAircraft(labelGroup);
  const material = new LineBasicMaterial({
    color: COLOR,
    transparent: true,
    opacity: 0.75,
    depthWrite: false,
    clippingPlanes: DIORAMA_PLANES,
  });
  let lines: LineSegments | null = null;
  let attached = false;
  const tmp = new Vector3();

  const dispose = (): void => {
    if (lines) {
      lines.removeFromParent();
      lines.geometry.dispose();
      lines = null;
    }
    for (const child of Array.from(labelGroup.children)) {
      labelGroup.remove(child);
      if (child instanceof CSS2DObject) child.element.remove();
    }
  };

  const rebuild = (): void => {
    dispose();
    if (!attached || !centres) return;
    const positions: number[] = [];
    const reach = RANGE_NM * 1.05;
    for (const c of centres) {
      // The point of this centre's boundary nearest the scope's middle: its name goes just inside it.
      let nearest: { lat: number; lon: number; d: number } | null = null;
      let latSum = 0;
      let lonSum = 0;
      let n = 0;
      for (const ring of c.rings) {
        for (let i = 0; i + 1 < ring.length; i++) {
          const [aLat, aLon] = ring[i]!;
          const [bLat, bLon] = ring[i + 1]!;
          latSum += aLat;
          lonSum += aLon;
          n++;
          const da = distanceFromHomeNm(aLat, aLon);
          const nm = Math.hypot((bLat - aLat) * 60, (bLon - aLon) * 60 * Math.cos((aLat * Math.PI) / 180));
          // A long straight edge can cross the scope with both ends outside it.
          if (da > reach + nm) continue;
          const pieces = Math.max(1, Math.ceil(nm / MAX_PIECE_NM));
          for (let k = 0; k < pieces; k++) {
            const lat0 = aLat + ((bLat - aLat) * k) / pieces;
            const lon0 = aLon + ((bLon - aLon) * k) / pieces;
            const lat1 = aLat + ((bLat - aLat) * (k + 1)) / pieces;
            const lon1 = aLon + ((bLon - aLon) * (k + 1)) / pieces;
            const d0 = distanceFromHomeNm(lat0, lon0);
            if (d0 > reach && distanceFromHomeNm(lat1, lon1) > reach) continue;
            terrainSurface(lat0, lon0, tmp);
            positions.push(tmp.x, tmp.y + 0.05, tmp.z);
            terrainSurface(lat1, lon1, tmp);
            positions.push(tmp.x, tmp.y + 0.05, tmp.z);
            if (d0 <= RANGE_NM * 0.9 && (!nearest || d0 < nearest.d)) nearest = { lat: lat0, lon: lon0, d: d0 };
          }
        }
      }
      if (!nearest || n === 0) continue;
      // Step from the boundary toward the middle of the centre.
      const toLat = latSum / n - nearest.lat;
      const toLon = (lonSum / n - nearest.lon) * Math.cos((nearest.lat * Math.PI) / 180);
      const len = Math.hypot(toLat, toLon) * 60 || 1;
      const lat = nearest.lat + (toLat * 60 * LABEL_INSET_NM) / len / 60;
      const lon = nearest.lon + (toLon * 60 * LABEL_INSET_NM) / len / 60 / Math.cos((nearest.lat * Math.PI) / 180);
      const el = document.createElement('div');
      el.className = 'aircraft-label centre-label';
      el.textContent = `${c.id} · ${c.name}`;
      const label = new CSS2DObject(el);
      terrainSurface(lat, lon, tmp);
      label.position.set(tmp.x, tmp.y + 0.3, tmp.z);
      labelGroup.add(label);
    }
    if (positions.length === 0) return;
    const geom = new BufferGeometry();
    geom.setAttribute('position', new BufferAttribute(new Float32Array(positions), 3));
    lines = new LineSegments(geom, material);
    lines.frustumCulled = false;
    lines.renderOrder = 5;
    lines.raycast = () => {};
    lines.userData = { kind: 'artcc' };
    group.add(lines);
  };

  const sync = (): void => {
    const on = centresActive();
    if (on) load();
    if (on === attached) return;
    attached = on;
    if (on) parent.add(group);
    else group.removeFromParent();
    rebuild();
  };

  subscribeCentres(rebuild);
  subscribeHome(rebuild);
  let lastKey = '';
  subscribeSettings(() => {
    sync();
    const s = getSettings();
    // The terrain the lines lie on moves with these.
    const key = `${s.altitudeExaggeration}|${s.altitudeCurveBias}|${s.terrain3d}`;
    if (key === lastKey) return;
    lastKey = key;
    rebuild();
  });
  sync();
}
